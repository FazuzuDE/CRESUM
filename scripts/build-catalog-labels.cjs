/* Deterministically extract reference labels; never modify domain records. */
const fs = require('node:fs');
const ts = require('typescript');
const rows = {};
function extract(file, kind, predicate = () => true) {
  const source = ts.createSourceFile(
    file,
    fs.readFileSync(file, 'utf8'),
    ts.ScriptTarget.Latest,
    true,
  );
  function visit(node) {
    if (ts.isObjectLiteralExpression(node)) {
      const fields = Object.fromEntries(
        node.properties
          .filter(ts.isPropertyAssignment)
          .map((p) => [
            p.name.getText(source).replace(/['"]/g, ''),
            ts.isStringLiteral(p.initializer) ? p.initializer.text : null,
          ]),
      );
      const label = fields.name ?? fields.label;
      if (fields.id && label && predicate(fields.id))
        rows[`catalog.${kind}.${fields.id}`] = label;
    }
    ts.forEachChild(node, visit);
  }
  visit(source);
}
extract('lib/exercise-library.ts', 'exercise');
const equipment = new Set([
  'barbell',
  'dumbbell',
  'bench',
  'step-platform',
  'cable',
  'machine',
  'smith-machine',
  'bodyweight',
  'kettlebell',
  'ez-bar',
  'resistance-band',
]);
extract('lib/exercise-taxonomy.ts', 'muscle', (id) => !equipment.has(id));
extract('lib/exercise-taxonomy.ts', 'equipment', (id) => equipment.has(id));
extract('lib/workout-catalog.ts', 'template');
for (const [goal, label] of Object.entries({
  build_muscle: 'Build muscle',
  get_stronger: 'Get stronger',
  general_fitness: 'General fitness',
}))
  for (const experience of ['beginner', 'some', 'experienced'])
    rows[`catalog.program.gym-${goal}-${experience}`] = label;
const text =
  '// Generated by scripts/build-catalog-labels.cjs.\nexport default ' +
  JSON.stringify(rows, null, 2) +
  ' as const;\n';
const output = 'lib/i18n/locales/en/catalog.ts';
if (process.argv.includes('--check')) {
  if (fs.readFileSync(output, 'utf8') !== text)
    throw Error('English catalog labels are stale; rebuild them.');
} else fs.writeFileSync(output, text);
console.log(`${Object.keys(rows).length} reference catalog labels.`);
