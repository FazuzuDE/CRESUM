/* Deterministically extract reference labels; never modify domain records. */
const fs = require('node:fs');
const ts = require('typescript');
const rows = {};
function extract(file, kind) {
  const source = ts.createSourceFile(
    file,
    fs.readFileSync(file, 'utf8'),
    ts.ScriptTarget.Latest,
    true,
  );
  function visit(node) {
    if (ts.isObjectLiteralExpression(node)) {
      const fields = Object.fromEntries(
        node.properties
          .filter(ts.isPropertyAssignment)
          .map((p) => [
            p.name.getText(source).replace(/['"]/g, ''),
            ts.isStringLiteral(p.initializer) ? p.initializer.text : null,
          ]),
      );
      const label = fields.name ?? fields.label;
      if (fields.id && label) rows[`catalog.${kind}.${fields.id}`] = label;
    }
    ts.forEachChild(node, visit);
  }
  visit(source);
}
extract('lib/exercise-library.ts', 'exercise');
function loadData(file) {
  const code = ts.transpileModule(fs.readFileSync(file, 'utf8'), {
    compilerOptions: {
      module: ts.ModuleKind.CommonJS,
      target: ts.ScriptTarget.ES2022,
    },
  }).outputText;
  const exports = {};
  new Function('exports', code)(exports);
  return exports;
}

const { muscleTaxonomy, equipmentTaxonomy } = loadData(
  'lib/exercise-taxonomy.ts',
);
for (const { id, label } of muscleTaxonomy)
  rows[`catalog.muscle.${id}`] = label;
for (const { id, label } of equipmentTaxonomy)
  rows[`catalog.equipment.${id}`] = label;
extract('lib/workout-catalog.ts', 'template');
const { trainingPrograms } = loadData('lib/training-programs/catalog.ts');
for (const { id, name } of trainingPrograms)
  rows[`catalog.program.${id}`] = name;
const text =
  '// Generated by scripts/build-catalog-labels.cjs.\nexport default ' +
  JSON.stringify(rows, null, 2) +
  ' as const;\n';
const output = 'lib/i18n/locales/en/catalog.ts';
if (process.argv.includes('--check')) {
  if (fs.readFileSync(output, 'utf8') !== text)
    throw Error('English catalog labels are stale; rebuild them.');
} else fs.writeFileSync(output, text);
console.log(`${Object.keys(rows).length} reference catalog labels.`);
