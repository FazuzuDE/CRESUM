/* Generate reference text without changing the authored technique catalog. */
const fs = require('node:fs');
const ts = require('typescript');
function referenceMessages() {
  const code = ts.transpileModule(
    fs.readFileSync('lib/exercise-technique/catalog.ts', 'utf8'),
    {
      compilerOptions: {
        module: ts.ModuleKind.CommonJS,
        target: ts.ScriptTarget.ES2022,
      },
    },
  ).outputText;
  const exports = {};
  new Function('exports', code)(exports);
  const messages = {};
  for (const [id, guide] of Object.entries(exports.techniqueCatalog))
    for (const field of [
      'scope',
      'setup',
      'movement',
      'checks',
      'mistakes',
      'adaptation',
    ]) {
      const value = guide[field];
      if (typeof value === 'string') messages[`guide.${id}.${field}`] = value;
      else if (value)
        value.forEach((text, index) => {
          messages[`guide.${id}.${field}.${index}`] = text;
        });
    }
  return messages;
}
const output = 'lib/i18n/locales/en/technique-content.ts';
const messages = referenceMessages();
const generated =
  '// Generated by scripts/build-technique-messages.cjs.\nexport default ' +
  JSON.stringify(messages, null, 2) +
  ' as const;\n';
if (process.argv.includes('--check')) {
  if (fs.readFileSync(output, 'utf8') !== generated)
    throw Error(
      'English technique text is stale; rebuild and review all target translations.',
    );
} else fs.writeFileSync(output, generated);
console.log(`${Object.keys(messages).length} authored technique messages.`);
